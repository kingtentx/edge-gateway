    [Fact]
    public async Task Scan_subsets_do_not_bridge_missing_disabled_or_not_due_points()
    {
        await using var server = new TcpServer(async (stream, token) =>
        {
            foreach (var (start, count) in new[] { (0, 3), (0, 1), (2, 1), (65534, 2) })
            {
                var request = await ReadRequestAsync(stream, token);
                Assert.Equal(start, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(8)));
                Assert.Equal(count, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(10)));
                var pdu = new byte[2 + count * 2]; pdu[0] = 3; pdu[1] = (byte)(count * 2);
                await stream.WriteAsync(Response(request, pdu), token);
            }
            await AssertPeerClosedAsync(stream, token);
        });
        var tags = new List<TagConfiguration>
        {
            new() { Address = "0" }, new() { Address = "1" }, new() { Address = "2" },
            new() { Address = "3", Enabled = false }, new() { Address = "65535" }, new() { Address = "65534" }
        };
        await using (var driver = new ModbusTcpDriverFactory().Create(server.Configuration(tags)))
        {
            await driver.ConnectAsync(server.Token);
            Assert.Equal(3, (await driver.ReadAsync(tags.Take(4).ToArray(), server.Token)).Count);
            var subset = new[] { tags[2], tags[0], tags[3], tags[4], tags[5] };
            var values = await driver.ReadAsync(subset, server.Token);
            Assert.Equal(subset.Where(tag => tag.Enabled).Select(tag => tag.Id), values.Select(value => value.TagId));
            Assert.Empty(await driver.ReadAsync([], server.Token));
            Assert.Empty(await driver.ReadAsync([tags[3]], server.Token));
        }
        await server.Completion;
    }

    [Fact]
    public async Task Device_rejecting_block_length_falls_back_to_individual_reads()
    {
        await using var server = new TcpServer(async (stream, token) =>
        {
            var batch = await ReadRequestAsync(stream, token);
            Assert.Equal((ushort)2, BinaryPrimitives.ReadUInt16BigEndian(batch.AsSpan(10)));
            await stream.WriteAsync(Response(batch, [0x83, 3]), token);
            for (ushort address = 0; address < 2; address++)
            {
                var request = await ReadRequestAsync(stream, token);
                Assert.Equal(address, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(8)));
                Assert.Equal((ushort)1, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(10)));
                await stream.WriteAsync(Response(request, [3, 2, 0, (byte)(address + 10)]), token);
            }
            await AssertPeerClosedAsync(stream, token);
        });
        var tags = new List<TagConfiguration> { new() { Address = "0" }, new() { Address = "1" } };
        await using (var driver = new ModbusTcpDriverFactory().Create(server.Configuration(tags)))
        {
            await driver.ConnectAsync(server.Token);
            var values = await driver.ReadAsync(tags, server.Token);
            Assert.All(values, value => Assert.Equal(SampleQuality.Good, value.Quality));
            Assert.Equal(new ushort[] { 10, 11 }, values.Select(value => Assert.IsType<ushort>(value.Value)));
        }
        await server.Completion;
    }

