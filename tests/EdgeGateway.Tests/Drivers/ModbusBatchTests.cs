    [Theory]
    [InlineData(100, 1)]
    [InlineData(1000, 8)]
    public async Task Dense_register_scan_uses_expected_number_of_wire_requests(int pointCount, int expectedRequests)
    {
        var requests = 0;
        await using var server = new TcpServer(async (stream, token) =>
        {
            var nextAddress = 0;
            for (var batch = 0; batch < expectedRequests; batch++)
            {
                var request = await ReadRequestAsync(stream, token);
                requests++;
                var count = Math.Min(125, pointCount - nextAddress);
                Assert.Equal(nextAddress, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(8)));
                Assert.Equal(count, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(10)));
                var pdu = new byte[2 + count * 2]; pdu[0] = 3; pdu[1] = (byte)(count * 2);
                for (var offset = 0; offset < count; offset++)
                    BinaryPrimitives.WriteUInt16BigEndian(pdu.AsSpan(2 + offset * 2), (ushort)(nextAddress + offset));
                await stream.WriteAsync(Response(request, pdu), token);
                nextAddress += count;
            }
            Assert.Equal(pointCount, nextAddress);
            await AssertPeerClosedAsync(stream, token);
        });
        var tags = Enumerable.Range(0, pointCount).Select(index => new TagConfiguration { Address = index.ToString() }).ToList();
        await using (var driver = new ModbusTcpDriverFactory().Create(server.Configuration(tags)))
        {
            await driver.ConnectAsync(server.Token);
            var values = await driver.ReadAsync(tags, server.Token);
            Assert.Equal(pointCount, values.Count);
            Assert.Equal(Enumerable.Range(0, pointCount).Select(index => (ushort)index), values.Select(value => Assert.IsType<ushort>(value.Value)));
        }
        await server.Completion;
        Assert.Equal(expectedRequests, requests);
    }

    [Fact]
    public async Task Cancellation_during_fallback_stops_remaining_reads_and_closes_connection()
    {
        using var cancellation = new CancellationTokenSource();
        await using var server = new TcpServer(async (stream, token) =>
        {
            var batch = await ReadRequestAsync(stream, token);
            await stream.WriteAsync(Response(batch, [0x83, 2]), token);
            var first = await ReadRequestAsync(stream, token);
            Assert.Equal((ushort)1, BinaryPrimitives.ReadUInt16BigEndian(first.AsSpan(10)));
            cancellation.Cancel();
            await AssertPeerClosedAsync(stream, token);
        });
        var tags = new List<TagConfiguration> { new() { Address = "0" }, new() { Address = "1" } };
        await using var driver = new ModbusTcpDriverFactory().Create(server.Configuration(tags));
        await driver.ConnectAsync(server.Token);
        await Assert.ThrowsAnyAsync<OperationCanceledException>(() => driver.ReadAsync(tags, cancellation.Token));
        await Assert.ThrowsAsync<IOException>(() => driver.ReadAsync(tags, server.Token));
        await server.Completion;
    }

    [Fact]
    public async Task Contiguous_mixed_types_and_overlapping_aliases_share_one_fragmented_request()
    {
        // Independent wire values, not generated by the production codec.
        var wire = Convert.FromHexString("1234FFFE03040102803F0000000000000000F03F00017FC0000080000000");
        await using var server = new TcpServer(async (stream, token) =>
        {
            var request = await ReadRequestAsync(stream, token);
            Assert.Equal(Convert.FromHexString("030064000F"), request.AsSpan(7).ToArray());
            var frame = Response(request, new byte[] { 3, 30 }.Concat(wire).ToArray());
            foreach (var value in frame) await stream.WriteAsync(new[] { value }, token);
            await AssertPeerClosedAsync(stream, token); // No extra request for aliases or adjacent points.
        });
        var tags = new List<TagConfiguration>
        {
            new() { Address = "106", DataType = TagDataType.Float64, ByteOrder = RegisterByteOrder.DCBA },
            new() { Address = "100", DataType = TagDataType.UInt16 },
            new() { Address = "104", DataType = TagDataType.Float32, ByteOrder = RegisterByteOrder.BADC },
            new() { Address = "101", DataType = TagDataType.Int16 },
            new() { Address = "102", DataType = TagDataType.UInt32, ByteOrder = RegisterByteOrder.CDAB },
            new() { Address = "110", DataType = TagDataType.Boolean },
            new() { Address = "111", DataType = TagDataType.Float32 },
            new() { Address = "113", DataType = TagDataType.Int32 },
            new() { Address = "100", DataType = TagDataType.UInt16, ByteOrder = RegisterByteOrder.BADC },
            new() { Address = "103", DataType = TagDataType.UInt16 }
        };
        await using (var driver = new ModbusTcpDriverFactory().Create(server.Configuration(tags)))
        {
            await driver.ConnectAsync(server.Token);
            var values = await driver.ReadAsync(tags, server.Token);
            Assert.Equal(tags.Select(tag => tag.Id), values.Select(value => value.TagId));
            Assert.Equal(1d, Assert.IsType<double>(values[0].Value));
            Assert.Equal((ushort)0x1234, Assert.IsType<ushort>(values[1].Value));
            Assert.Equal(1f, Assert.IsType<float>(values[2].Value));
            Assert.Equal((short)-2, Assert.IsType<short>(values[3].Value));
            Assert.Equal(0x01020304u, Assert.IsType<uint>(values[4].Value));
            Assert.True(Assert.IsType<bool>(values[5].Value));
            Assert.Equal(SampleQuality.Bad, values[6].Quality);
            Assert.Null(values[6].Value);
            Assert.Equal(int.MinValue, Assert.IsType<int>(values[7].Value));
            Assert.Equal((ushort)0x3412, Assert.IsType<ushort>(values[8].Value));
            Assert.Equal((ushort)0x0102, Assert.IsType<ushort>(values[9].Value));
            Assert.All(values.Where((_, index) => index != 6), value => Assert.Equal(SampleQuality.Good, value.Quality));
        }
        await server.Completion;
    }

    [Theory]
    [InlineData(ModbusArea.Coil, 1, 2000)]
    [InlineData(ModbusArea.DiscreteInput, 2, 2000)]
    [InlineData(ModbusArea.HoldingRegister, 3, 125)]
    [InlineData(ModbusArea.InputRegister, 4, 125)]
    public async Task Requests_split_at_protocol_limit_and_preserve_input_order(ModbusArea area, byte function, int limit)
    {
        var bit = function <= 2;
        await using var server = new TcpServer(async (stream, token) =>
        {
            foreach (var (start, count) in new[] { (0, limit), (limit, 1) })
            {
                var request = await ReadRequestAsync(stream, token);
                Assert.Equal(function, request[7]);
                Assert.Equal(start, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(8)));
                Assert.Equal(count, BinaryPrimitives.ReadUInt16BigEndian(request.AsSpan(10)));
                var pdu = new byte[2 + (bit ? (count + 7) / 8 : count * 2)];
                pdu[0] = function; pdu[1] = checked((byte)(pdu.Length - 2));
                for (var index = 0; index < count; index++)
                    if (bit) { if ((start + index) % 2 == 0) pdu[2 + index / 8] |= (byte)(1 << (index % 8)); }
                    else BinaryPrimitives.WriteUInt16BigEndian(pdu.AsSpan(2 + index * 2), (ushort)(start + index));
                await stream.WriteAsync(Response(request, pdu), token);
            }
            await AssertPeerClosedAsync(stream, token);
        });
        var tags = Enumerable.Range(0, limit + 1).Reverse().Select(index => new TagConfiguration
        { Address = index.ToString(), Area = area, DataType = bit ? TagDataType.Boolean : TagDataType.UInt16 }).ToList();
        await using (var driver = new ModbusTcpDriverFactory().Create(server.Configuration(tags)))
        {
            await driver.ConnectAsync(server.Token);
            var values = await driver.ReadAsync(tags, server.Token);
            for (var index = 0; index < values.Count; index++)
            {
                Assert.Equal(tags[index].Id, values[index].TagId);
                if (bit) Assert.Equal((limit - index) % 2 == 0, Assert.IsType<bool>(values[index].Value));
                else Assert.Equal((ushort)(limit - index), Assert.IsType<ushort>(values[index].Value));
            }
        }
        await server.Completion;
    }

    [Fact]
    public async Task Multi_register_value_is_not_split_across_batches()
    {
        await using var server = new TcpServer(async (stream, token) =>
        {
            var first = await ReadRequestAsync(stream, token);
            Assert.Equal(Convert.FromHexString("030000007C"), first.AsSpan(7).ToArray());
            var pdu = new byte[250]; pdu[0] = 3; pdu[1] = 248;
            await stream.WriteAsync(Response(first, pdu), token);
            var second = await ReadRequestAsync(stream, token);
            Assert.Equal(Convert.FromHexString("03007C0004"), second.AsSpan(7).ToArray());
            await stream.WriteAsync(Response(second, Convert.FromHexString("03083FF0000000000000")), token);
        });
        var tags = Enumerable.Range(0, 124).Select(index => new TagConfiguration { Address = index.ToString() }).ToList();
        tags.Add(new() { Address = "124", DataType = TagDataType.Float64 });
        await using var driver = new ModbusTcpDriverFactory().Create(server.Configuration(tags));
        await driver.ConnectAsync(server.Token);
        var values = await driver.ReadAsync(tags, server.Token);
        Assert.Equal(1d, Assert.IsType<double>(values[^1].Value));
        Assert.All(values, value => Assert.Equal(SampleQuality.Good, value.Quality));
        await server.Completion;
    }

